// Generates src/core/shared/go-isprint.ts from Go's strconv/isprint.go.
//
// Go `strconv.Quote` keeps a rune as is only when `strconv.IsPrint` says it is
// printable, and IsPrint reads fixed tables built from the Unicode version of
// that Go release (Go 1.24.1: Unicode 15.0.0). Node's own Unicode data is
// newer, so a character added later (for example U+1FAE9, Unicode 16) is
// printable to Node but escaped by Go. The TypeScript CLI therefore uses Go's
// tables, copied here, not Node's Unicode properties.
//
// Usage, from toolkits/buildos/:
//   node scripts/generate-go-isprint.ts <GOROOT>
// The GOROOT must be the Go release the seed goldens were captured with.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const TABLES = ["isPrint16", "isNotPrint16", "isPrint32", "isNotPrint32"] as const;

/** Reads the numbers of one `var name = []uintN{ ... }` table. */
export function readGoTable(source: string, name: string): number[] {
  const match = new RegExp(`var ${name} = \\[\\]uint(?:16|32)\\{[^\\n]*\\n([\\s\\S]*?)\\n\\}`).exec(source);
  if (match === null) throw new Error(`table ${name} not found`);
  const body = match[1]!.replace(/\/\/[^\n]*/g, "");
  return body
    .split(/[\s,]+/)
    .filter((token) => token !== "")
    .map((token) => {
      const value = Number(token);
      if (!Number.isInteger(value) || value < 0) throw new Error(`table ${name} has a bad entry ${JSON.stringify(token)}`);
      return value;
    });
}

/** Encodes ascending numbers as base-36 deltas, so the table stays small. */
export function encodeDeltas(values: readonly number[]): string {
  let previous = 0;
  return values
    .map((value) => {
      if (value < previous) throw new Error("table is not ascending");
      const delta = value - previous;
      previous = value;
      return delta.toString(36);
    })
    .join(",");
}

/**
 * The header of src/core/shared/go-isprint.ts. It names the Go source files and the
 * Go license. The `/*!` legal comment makes esbuild keep the notice in
 * dist/buildos.js. THIRD_PARTY_NOTICES.md holds the full license text.
 */
export function goIsprintHeader(goVersion: string, unicodeVersion: string): string {
  return `// Generated by scripts/generate-go-isprint.ts from ${goVersion} src/strconv/isprint.go
// (Unicode ${unicodeVersion}). Do not edit by hand.
//
// Each table is Go's table as base-36 deltas. See decodeGoTable in go-quote.ts.

/*! Unicode printable-rune tables from the Go standard library (${goVersion}),
 * src/strconv/isprint.go, generated by src/strconv/makeisprint.go.
 * Copyright 2009 The Go Authors. Licensed under the BSD-3-Clause license.
 * The full license text is in THIRD_PARTY_NOTICES.md.
 * @license BSD-3-Clause
 */
`;
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const goroot = process.argv[2];
  if (goroot === undefined) {
    process.stderr.write("usage: node scripts/generate-go-isprint.ts <GOROOT>\n");
    process.exit(2);
  }
  const source = readFileSync(join(goroot, "src", "strconv", "isprint.go"), "utf8");
  const goVersion = readFileSync(join(goroot, "VERSION"), "utf8").split("\n")[0]!.trim();
  const unicodeVersion = /Version = "([^"]+)"/.exec(readFileSync(join(goroot, "src", "unicode", "tables.go"), "utf8"))?.[1];
  const lines = TABLES.map((name) => `  ${name}: "${encodeDeltas(readGoTable(source, name))}",`);
  const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "core", "shared", "go-isprint.ts");
  writeFileSync(
    out,
    `${goIsprintHeader(goVersion, unicodeVersion ?? "unknown")}
export const GO_ISPRINT_VERSION = ${JSON.stringify(goVersion)};

export const GO_ISPRINT_TABLES = {
${lines.join("\n")}
} as const;
`,
  );
  process.stdout.write(`wrote ${out}\n`);
}
