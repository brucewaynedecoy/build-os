// Generates src/core/shared/go-fold.ts from Go's unicode.SimpleFold.
//
// Go `encoding/json` matches an object key to a struct field first by exact
// name, then by `foldName` (src/encoding/json/fold.go): ASCII letters to upper
// case, and every other rune to the smallest rune of its `unicode.SimpleFold`
// orbit. The orbits come from the case tables of that Go release (Go 1.24.1:
// Unicode 15.0.0). JavaScript case mapping is not simple folding (for
// example, "ı".toUpperCase() is "I", but SimpleFold('ı') is 'ı'), and Node's
// Unicode data is newer, so the TypeScript CLI uses Go's own result, copied
// here.
//
// Usage, from toolkits/buildos/:
//   node scripts/generate-go-fold.ts <GOROOT>
// The GOROOT must be the Go release the seed goldens were captured with. The
// script runs `<GOROOT>/bin/go run` on a small program that prints, for every
// non-ASCII rune whose fold is not itself, the rune and Go's `foldRune`.

import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** The Go program: `foldRune` exactly as src/encoding/json/fold.go has it. */
const PROGRAM = `package main

import (
	"fmt"
	"unicode"
)

func foldRune(r rune) rune {
	for {
		r2 := unicode.SimpleFold(r)
		if r2 <= r {
			return r2
		}
		r = r2
	}
}

func main() {
	for r := rune(0x80); r <= unicode.MaxRune; r++ {
		if f := foldRune(r); f != r {
			fmt.Printf("%d %d\\n", r, f)
		}
	}
}
`;

/** Encodes `[rune, fold]` pairs as `<rune delta>:<fold>` in base 36, runes ascending. */
export function encodeFoldPairs(pairs: readonly (readonly [number, number])[]): string {
  let previous = 0;
  return pairs
    .map(([rune, fold]) => {
      if (rune <= previous && previous !== 0) throw new Error("runes are not ascending");
      const delta = rune - previous;
      previous = rune;
      return `${delta.toString(36)}:${fold.toString(36)}`;
    })
    .join(",");
}

/** The header of src/core/shared/go-fold.ts: the Go source and license, kept in the bundle as a legal comment. */
export function goFoldHeader(goVersion: string, unicodeVersion: string): string {
  return `// Generated by scripts/generate-go-fold.ts from ${goVersion} src/unicode/tables.go
// (Unicode ${unicodeVersion}) through unicode.SimpleFold and the foldRune of
// src/encoding/json/fold.go. Do not edit by hand.
//
// Each entry is <rune delta>:<fold> in base 36. See goFoldRune in go-json.ts.

/*! Unicode simple case-folding orbits from the Go standard library (${goVersion}),
 * src/unicode/tables.go and src/unicode/letter.go (SimpleFold), and
 * src/encoding/json/fold.go (foldRune).
 * Copyright 2009 The Go Authors. Licensed under the BSD-3-Clause license.
 * The full license text is in THIRD_PARTY_NOTICES.md.
 * @license BSD-3-Clause
 */
`;
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const goroot = process.argv[2];
  if (goroot === undefined) {
    process.stderr.write("usage: node scripts/generate-go-fold.ts <GOROOT>\n");
    process.exit(2);
  }
  const goVersion = readFileSync(join(goroot, "VERSION"), "utf8").split("\n")[0]!.trim();
  const unicodeVersion = /Version = "([^"]+)"/.exec(readFileSync(join(goroot, "src", "unicode", "tables.go"), "utf8"))?.[1] ?? "unknown";
  const work = mkdtempSync(join(tmpdir(), "buildos-go-fold-"));
  try {
    writeFileSync(join(work, "main.go"), PROGRAM);
    const run = spawnSync(join(goroot, "bin", "go"), ["run", "main.go"], {
      cwd: work,
      encoding: "utf8",
      env: { ...process.env, GOROOT: goroot, GOTOOLCHAIN: "local", GO111MODULE: "off", GOCACHE: process.env["GOCACHE"] ?? join(work, "cache") },
      maxBuffer: 64 * 1024 * 1024,
    });
    if (run.status !== 0) throw new Error(`go run failed: ${run.stderr}`);
    const pairs = run.stdout
      .trim()
      .split("\n")
      .map((line) => line.split(" ").map(Number) as [number, number]);
    const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "core", "shared", "go-fold.ts");
    writeFileSync(
      out,
      `${goFoldHeader(goVersion, unicodeVersion)}
export const GO_FOLD_VERSION = ${JSON.stringify(goVersion)};

/** ${pairs.length} non-ASCII runes whose Go fold is another rune. */
export const GO_FOLD_TABLE = "${encodeFoldPairs(pairs)}";
`,
    );
    process.stdout.write(`wrote ${out} (${pairs.length} runes)\n`);
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
}
